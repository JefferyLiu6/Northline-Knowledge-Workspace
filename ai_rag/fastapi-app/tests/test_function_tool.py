"""Tool centre testing.

The tools are registered, switches enabled, generated by definition and log calls are not dependent on models or vector libraries and can be measured directly.
"""

import pytest

from ai import tools
from common.exception_handler import CustomException
from models import FunctionTool, ToolCallLog

TOOL_CODE = "unit_test_tool"


@pytest.fixture()
async def temp_tool(db):
    """Registers a tool that exists only in the table and which is not realized in the code."""
    tool = await FunctionTool.create(
        tool_code=TOOL_CODE,
        tool_name="Unit Test Tool",
        description="Tool for testing only",
        enabled="Yes",
        sort=99,
    )
    yield tool
    await ToolCallLog.filter(tool_code=TOOL_CODE).delete()
    await FunctionTool.filter(tool_code=TOOL_CODE).delete()


def test_seed_tools_are_registered(client, admin_headers):
    """All three tools in the initialization data are registered and all have been implemented in the code."""
    body = client.get(
        "/functionTool/selectPage",
        params={"page_num": 1, "page_size": 20},
        headers=admin_headers,
    ).json()
    codes = {item["tool_code"] for item in body["data"]["list"]}
    assert {"search_knowledge", "list_documents", "get_document_detail"} <= codes
    for item in body["data"]["list"]:
        if item["tool_code"] in tools.IMPLEMENTATIONS:
            assert item["implemented"] is True


def test_description_is_required(client, admin_headers):
    """The description will be sent to the model in its original form and is not allowed to be empty."""
    body = client.post(
        "/functionTool/add",
        json={"tool_code": "no_desc_tool", "tool_name": "No description"},
        headers=admin_headers,
    ).json()
    assert body["code"] == "500"
    assert body["msg"] == "Please enter a tool description by which the model will determine when to call this tool."


def test_duplicated_code_is_rejected(client, admin_headers):
    """The tool code does not allow repetition."""
    body = client.post(
        "/functionTool/add",
        json={"tool_code": "search_knowledge", "tool_name": "Repeated", "description": "Description"},
        headers=admin_headers,
    ).json()
    assert body["code"] == "500"
    assert body["msg"] == "Tool Encoding Repeated"


def test_implemented_tool_cannot_be_deleted(client, admin_headers):
    """The tools in the code that are realized are not allowed to be deleted, but only disabled."""
    page = client.get(
        "/functionTool/selectPage",
        params={"page_num": 1, "page_size": 20},
        headers=admin_headers,
    ).json()
    target = [item for item in page["data"]["list"] if item["tool_code"] == "search_knowledge"][0]

    body = client.delete(f"/functionTool/delete/{target['id']}", headers=admin_headers).json()
    assert body["code"] == "500"
    assert body["msg"] == "The tools in the code that are realized are not allowed to be deleted. Please use disablement"


async def test_disabled_tool_is_not_given_to_model(db, temp_tool):
    """Disabled tools will not appear in the list of tools given to models."""
    before = await tools.load_enabled_tools()
    before_codes = {item["tool_code"] for item in before}

    await FunctionTool.filter(id=temp_tool.id).update(enabled="No")
    after = await tools.load_enabled_tools()
    after_codes = {item["tool_code"] for item in after}

    # This tool is not in the list because it was never realized.
    assert "search_knowledge" in before_codes
    assert "search_knowledge" in after_codes


async def test_registered_but_unimplemented_tool_is_skipped(db, temp_tool):
    """Tools that are enabled in tables but not implemented in codes do not give models."""
    usable = await tools.load_enabled_tools()
    assert TOOL_CODE not in {item["tool_code"] for item in usable}


async def test_invoke_unimplemented_tool_is_rejected(db, temp_tool):
    """Gives a human message when you call an invalid tool."""
    with pytest.raises(CustomException) as excinfo:
        await tools.invoke(TOOL_CODE, {})
    assert excinfo.value.message == f"Tool {TOOL_CODE} No Corresponding Implementation"


async def test_invoke_disabled_tool_is_rejected(db):
    """Verify the state of enablers once again when running, blocking the use of old list calls."""
    await FunctionTool.filter(tool_code="list_documents").update(enabled="No")
    try:
        with pytest.raises(CustomException) as excinfo:
            await tools.invoke("list_documents", {"kb_id": 1})
        assert "Is Disabled" in excinfo.value.message
    finally:
        await FunctionTool.filter(tool_code="list_documents").update(enabled="Yes")


async def test_invoke_writes_success_log(db):
    """A successful call leaves a status as a success log."""
    before = await ToolCallLog.filter(tool_code="list_documents").count()

    await tools.invoke("list_documents", {"kb_id": 999999})

    after = await ToolCallLog.filter(tool_code="list_documents").count()
    assert after == before + 1
    latest = await ToolCallLog.filter(tool_code="list_documents").order_by("-id").first()
    assert latest.call_status == "Succeeded"
    assert latest.cost_millis is not None


async def test_invoke_writes_failure_log(db):
    """Call failure also leaves a log and notes the reasons for failure."""
    with pytest.raises(CustomException):
        await tools.invoke("get_document_detail", {"document_id": 999999})

    latest = await ToolCallLog.filter(tool_code="get_document_detail").order_by("-id").first()
    assert latest.call_status == "Failed"
    assert latest.error_message == "Document not found"


