"""Manage evaluation sets.

Evaluation cases have three sources, corresponding to three real-world scenarios:

    Manual entry: Business parties focus on a few key issues, entered one by one.
    Document generation: Let the model read the document and automatically generate question-answer pairs, quickly scaling up.
    Feedback accumulation: Issues clicked by users in Chapter 25, these are places where the system actually answered incorrectly.

The cases from the three sources are mixed in the same evaluation set, treated equally during scoring.
"""

import json
import re
from typing import List

from ai import model_factory, prompt_loader
from common.exception_handler import CustomException
from common.result import PageInfo
from models import (
    ChatMessage,
    EvalCase,
    EvalDataset,
    KnowledgeChunk,
    MessageFeedback,
)

# The maximum number of output produced automatically at a time is too slow and easy to use low quality
MAX_GENERATE_COUNT = 20
# Send model to generate question-and-answer session with maximum number of words
MAX_GENERATE_CHARS = 4000
SOURCES = {"Manual entry", "Generated from document", "From feedback"}


def dataset_dict(dataset: EvalDataset) -> dict:
    return {
        "id": dataset.id,
        "name": dataset.name,
        "kb_id": dataset.kb_id,
        "description": dataset.description,
        "case_count": dataset.case_count,
        "create_time": dataset.create_time,
        "update_time": dataset.update_time,
    }


def case_dict(case: EvalCase) -> dict:
    return {
        "id": case.id,
        "dataset_id": case.dataset_id,
        "question": case.question,
        "ground_truth": case.ground_truth,
        "reference_chunk_ids": case.reference_chunk_ids,
        "source": case.source,
        "enabled": case.enabled,
        "remark": case.remark,
        "create_time": case.create_time,
    }


async def reference_chunks(case_id: int) -> list[dict]:
    """Extract a fragment of the original text from a case's source to verify the correctness of the standard answer.

    The standard answer is generated by the model based on the fragment, and the model may misread the segment or confuse adjacent clauses.
    During manual review, the problem, standard answer, and original fragment text must be placed together to determine the judgment.
    """
    case = await EvalCase.get_or_none(id=case_id)
    if case is None:
        raise CustomException("Evaluation case not found")
    ids = [item.strip() for item in (case.reference_chunk_ids or "").split(",") if item.strip().isdigit()]
    if not ids:
        return []
    chunks = await KnowledgeChunk.filter(id__in=[int(item) for item in ids])
    # Returns in the order of reference_chunk_ids, with the order of labels
    order = {int(item): index for index, item in enumerate(ids)}
    chunks.sort(key=lambda chunk: order.get(chunk.id, 0))
    return [
        {
            "chunk_id": chunk.id,
            "document_id": chunk.document_id,
            "chunk_index": chunk.chunk_index,
            "chunk_type": chunk.chunk_type,
            "page_no": chunk.page_no,
            "content": chunk.content,
        }
        for chunk in chunks
    ]


async def _refresh_case_count(dataset_id: int) -> None:
    """Rerun the count of evaluation cases, recalculating after adding or removing cases."""
    count = await EvalCase.filter(dataset_id=dataset_id).count()
    await EvalDataset.filter(id=dataset_id).update(case_count=count)


async def add_dataset(payload: dict) -> None:
    if not payload.get("name"):
        raise CustomException("Please enter the evaluation set name")
    if await EvalDataset.get_or_none(name=payload["name"]):
        raise CustomException("Duplicate evaluation set name")
    await EvalDataset.create(
        name=payload["name"],
        kb_id=payload.get("kb_id"),
        description=payload.get("description"),
    )


async def update_dataset(dataset_id: int | None, payload: dict) -> None:
    if dataset_id is None:
        raise CustomException("Evaluation set ID cannot be empty")
    if await EvalDataset.get_or_none(id=dataset_id) is None:
        raise CustomException("Evaluation dataset not found")
    if not payload.get("name"):
        raise CustomException("Please enter the evaluation set name")
    if await EvalDataset.filter(name=payload["name"]).exclude(id=dataset_id).exists():
        raise CustomException("Duplicate evaluation set name")
    await EvalDataset.filter(id=dataset_id).update(
        name=payload["name"],
        kb_id=payload.get("kb_id"),
        description=payload.get("description"),
    )


async def delete_dataset(dataset_id: int) -> None:
    if await EvalDataset.get_or_none(id=dataset_id) is None:
        raise CustomException("Evaluation dataset not found")
    # We're going to delete it, no orphans.
    await EvalCase.filter(dataset_id=dataset_id).delete()
    await EvalDataset.filter(id=dataset_id).delete()


async def select_datasets() -> List[dict]:
    datasets = await EvalDataset.all().order_by("-id")
    return [dataset_dict(item) for item in datasets]


async def select_dataset_page(name: str = "", page_num: int = 1, page_size: int = 10) -> PageInfo:
    query = EvalDataset.filter(name__contains=name)
    items = await query.order_by("-id").offset((page_num - 1) * page_size).limit(page_size)
    total = await query.count()
    return PageInfo(total=total, list=[dataset_dict(item) for item in items])


async def add_case(payload: dict) -> None:
    dataset_id = payload.get("dataset_id")
    if not dataset_id:
        raise CustomException("Please select an evaluation set")
    if await EvalDataset.get_or_none(id=dataset_id) is None:
        raise CustomException("Evaluation dataset not found")
    if not payload.get("question"):
        raise CustomException("Please enter a question")
    # Context Recall, the indicator must have a standard answer to calculate. If not, it's only three indicators.
    if not payload.get("ground_truth"):
        raise CustomException("Please enter the standard answer; without it, the context recall metric cannot be calculated.")
    source = payload.get("source") or "Manual entry"
    if source not in SOURCES:
        raise CustomException("Source parameter error")
    await EvalCase.create(
        dataset_id=dataset_id,
        question=payload["question"],
        ground_truth=payload["ground_truth"],
        reference_chunk_ids=payload.get("reference_chunk_ids"),
        source=source,
        enabled=payload.get("enabled") or "Yes",
        remark=payload.get("remark"),
    )
    await _refresh_case_count(dataset_id)


async def update_case(case_id: int | None, payload: dict) -> None:
    if case_id is None:
        raise CustomException("Case ID cannot be empty")
    case = await EvalCase.get_or_none(id=case_id)
    if case is None:
        raise CustomException("Evaluation case not found")
    if not payload.get("question"):
        raise CustomException("Please enter a question")
    if not payload.get("ground_truth"):
        raise CustomException("Please enter the standard answer; without it, the context recall metric cannot be calculated.")
    await EvalCase.filter(id=case_id).update(
        question=payload["question"],
        ground_truth=payload["ground_truth"],
        reference_chunk_ids=payload.get("reference_chunk_ids"),
        enabled=payload.get("enabled") or "Yes",
        remark=payload.get("remark"),
    )


async def delete_case(case_id: int) -> None:
    case = await EvalCase.get_or_none(id=case_id)
    if case is None:
        raise CustomException("Evaluation case not found")
    await EvalCase.filter(id=case_id).delete()
    await _refresh_case_count(case.dataset_id)


async def select_case_page(
    dataset_id: int | None = None,
    source: str = "",
    keyword: str = "",
    page_num: int = 1,
    page_size: int = 10,
) -> PageInfo:
    query = EvalCase.all()
    if dataset_id:
        query = query.filter(dataset_id=dataset_id)
    if source:
        query = query.filter(source=source)
    if keyword:
        query = query.filter(question__contains=keyword)
    cases = await query.order_by("-id").offset((page_num - 1) * page_size).limit(page_size)
    total = await query.count()
    return PageInfo(total=total, list=[case_dict(case) for case in cases])


def parse_generated(text: str) -> List[dict]:
    """Parse the question-answer pairs generated by the model.

    The template requires returning a JSON array, but the model often wraps it in a ```json code block,
    or adds a sentence before or after. Here, extract the JSON array segment first before parsing.

    source_index is the model's marked source fragment number, pointing to [Fragment N] in the Prompt.
    It determines which fragments the Context Recall uses as references for this case; if the model does not mark or marks incorrectly,
    leave it blank, allowing Context Recall to revert to semantic judgment.
    """
    matched = re.search(r"\[.*\]", str(text), re.S)
    if not matched:
        return []
    try:
        items = json.loads(matched.group(0))
    except json.JSONDecodeError:
        return []
    pairs = []
    for item in items:
        if not isinstance(item, dict):
            continue
        question = str(item.get("question") or "").strip()
        ground_truth = str(item.get("ground_truth") or "").strip()
        # Two fields without one, it won't work. Throw them away.
        if not question or not ground_truth:
            continue
        # Source Snippet Serial Number, model may give a number, string, or a array
        raw = item.get("source_index")
        indexes = []
        for one in raw if isinstance(raw, list) else [raw]:
            text_one = str(one).strip()
            # You don't want any non-numeric content.
            if text_one.isdigit():
                indexes.append(int(text_one))
        pairs.append(
            {"question": question, "ground_truth": ground_truth, "source_indexes": indexes}
        )
    return pairs


async def generate_from_document(dataset_id: int, document_id: int, count: int) -> int:
    """Let the model read the document fragment and automatically generate question-answer pairs.

    The generated cases are tagged with the source fragment ID, providing Context Recall with a definite reference.
    """
    dataset = await EvalDataset.get_or_none(id=dataset_id)
    if dataset is None:
        raise CustomException("Evaluation dataset not found")
    count = max(1, min(count, MAX_GENERATE_COUNT))
    chunks = await KnowledgeChunk.filter(document_id=document_id).exclude(chunk_type="Parent chunk").order_by("chunk_index")
    if not chunks:
        raise CustomException("This document has no fragments; please parse and split first.")

    # The clip is numbered in Prompt by [snippet 1] [snippet 2] and the model is to indicate which part of each question-and-answer session it uses.
    # The serial number and the true kunk_id correspondence are recorded in id_of_index, rewrite back to real ID
    parts = []
    id_of_index: dict[int, int] = {}
    used = 0
    for chunk in chunks:
        if used + len(chunk.content) > MAX_GENERATE_CHARS:
            break
        index = len(parts) + 1
        parts.append(f"[Chunk {index}]\n{chunk.content}")
        id_of_index[index] = chunk.id
        used += len(chunk.content)

    prompt = await prompt_loader.render(
        "EVAL_CASE_GEN", count=count, context="\n\n".join(parts)
    )
    config = await model_factory.load_enabled(model_factory.CHAT)
    model = model_factory.build_chat_model(config)
    reply = await model.ainvoke(prompt)
    pairs = parse_generated(reply.content)
    if not pairs:
        raise CustomException("The model did not return usable question-answer pairs; please retry or adjust the EVAL_CASE_GEN template.")

    for pair in pairs[:count]:
        # This question-and-answer period is merely taken as a reference for the true use of the segment.
        # The whole piece of the document will increase the denominator of Context Recall:
        # The answer is only in one piece, but it's the full score that you ask to recall the whole story.
        reference_ids = [
            str(id_of_index[index]) for index in pair["source_indexes"] if index in id_of_index
        ]
        await EvalCase.create(
            dataset_id=dataset_id,
            question=pair["question"],
            ground_truth=pair["ground_truth"],
            # The model is empty when it is not marked or marked. Context Recall returns to semantic terms, without misreferencing
            reference_chunk_ids=",".join(reference_ids) if reference_ids else None,
            source="Generated from document",
            enabled="Yes",
        )
    await _refresh_case_count(dataset_id)
    return len(pairs[:count])


async def convert_from_feedback(dataset_id: int, feedback_ids: List[int] | None = None) -> int:
    """Accumulate the clicked issues into evaluation cases.

    Leave the standard answer blank for manual filling—system answered incorrectly, the correct answer is only known to humans.
    After completion, this case is considered complete, so accumulated cases are default disabled.
    """
    dataset = await EvalDataset.get_or_none(id=dataset_id)
    if dataset is None:
        raise CustomException("Evaluation dataset not found")
    query = MessageFeedback.filter(feedback_type="Dislike", converted="No")
    if feedback_ids:
        query = query.filter(id__in=feedback_ids)
    feedbacks = await query
    if not feedbacks:
        raise CustomException("No pending clicked issues to accumulate")

    message_ids = [item.message_id for item in feedbacks]
    messages = await ChatMessage.filter(id__in=message_ids)
    session_ids = {message.session_id for message in messages}
    # The answer to the last one is the corresponding question.
    all_messages = await ChatMessage.filter(session_id__in=session_ids).order_by("id")
    question_of: dict[int, str] = {}
    last_user = {}
    for message in all_messages:
        if message.role == "user":
            last_user[message.session_id] = message.content
        else:
            question_of[message.id] = last_user.get(message.session_id, "")

    created = 0
    for feedback in feedbacks:
        question = question_of.get(feedback.message_id)
        if not question:
            continue
        await EvalCase.create(
            dataset_id=dataset_id,
            question=question,
            # Standard answers are left blank, waiting for manual supplementation; after completion
            ground_truth="",
            source="From feedback",
            enabled="No",
            remark=f"From feedback #{feedback.id}" + (f": {feedback.reason}" if feedback.reason else ""),
        )
        await MessageFeedback.filter(id=feedback.id).update(converted="Yes")
        created += 1
    await _refresh_case_count(dataset_id)
    return created
